"""Generate a SYNTHETIC episode-level eval CSV for exercising the analysis
pipeline before real Phase B results exist.

    uv run python -m xembench.scripts.generate_toy_results \
        [--out outputs/toy/eval_episodes.csv]

EVERY NUMBER PRODUCED HERE IS FAKE. The data is deterministic, labeled toy
data whose only purpose is to test/demo the analysis CLIs and reports. A
TOY_DATA_README.txt is written next to the CSV, and reports generated from
it carry a synthetic-data banner. Do not mix this file with real results
directories (it defaults to outputs/, which is gitignored).
"""

import argparse
import sys
from pathlib import Path

import numpy as np

from xembench.analysis.episodes import append_episodes
from xembench.analysis.taxonomy import FailureType
from xembench.utils.config import resolve_path

# Hand-picked FAKE success rates: native > transfer, canonical > heldout,
# so summaries/transfer tables have visible, verifiable structure.
TOY_CELLS = [
    # task, eval_task, train_emb, eval_emb, instr, color, sr, n
    ("pick_cube_arm", "pick_cube_arm", "panda", "panda", "canonical", "train", 0.80, 40),
    ("pick_cube_arm", "pick_cube_arm", "panda", "panda", "heldout", "train", 0.65, 40),
    ("pick_cube_arm", "pick_cube_arm", "panda", "panda", "canonical", "unseen", 0.55, 40),
    ("pick_cube_arm", "apple_bowl_g1", "panda", "g1", "canonical", "train", 0.30, 40),
    ("apple_bowl_g1", "apple_bowl_g1", "g1", "g1", "canonical", "train", 0.70, 40),
    ("apple_bowl_g1", "pick_cube_arm", "g1", "panda", "canonical", "train", 0.25, 40),
]

FAILURE_POOL = [
    FailureType.TIMEOUT.value,
    FailureType.GRASP_FAILURE.value,
    FailureType.WRONG_OBJECT_SELECTED.value,
    FailureType.REACH_FAILURE.value,
    FailureType.OBJECT_DROPPED.value,
]


def generate(out_csv: Path, seed: int = 0) -> int:
    rng = np.random.default_rng(seed)
    rows = []
    for task, eval_task, temb, eemb, instr, color, sr, n in TOY_CELLS:
        n_success = round(sr * n)  # exact rates -> tests can assert equality
        max_steps = 50 if eemb == "panda" else 100
        for i in range(n):
            success = i < n_success
            rows.append(dict(
                policy_type="bc", task=task, train_embodiment=temb,
                eval_task=eval_task, eval_embodiment=eemb,
                instruction_cond=instr, color_cond=color, seed=0,
                checkpoint="TOY_DATA_NOT_A_REAL_CHECKPOINT",
                episode_idx=i, episode_seed=100_000 + i,
                success=int(success),
                steps=int(rng.integers(10, max_steps // 2)) if success else max_steps,
                max_steps=max_steps,
                failure_type="success" if success
                else FAILURE_POOL[int(rng.integers(len(FAILURE_POOL)))],
            ))
    if out_csv.exists():
        out_csv.unlink()  # regenerate deterministically, never append
    append_episodes(rows, out_csv)
    readme = out_csv.parent / "TOY_DATA_README.txt"
    readme.write_text(
        "The CSVs in this directory are SYNTHETIC toy data generated by\n"
        "xembench.scripts.generate_toy_results to exercise the analysis\n"
        "pipeline. They are not experimental results.\n"
    )
    return len(rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="outputs/toy/eval_episodes.csv")
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    out = Path(resolve_path(args.out))
    n = generate(out, args.seed)
    print(f"wrote {n} SYNTHETIC episode rows -> {out}")
    print("Reminder: toy data — every number is fake by construction.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
